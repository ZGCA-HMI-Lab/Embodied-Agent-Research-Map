"""Versioned browser export; canonical records are never edited here."""
import copy
import hashlib
import json
from pathlib import Path

from research_data import categories, paper_label

REPOSITORY = "https://github.com/ZGCA-HMI-Lab/Embodied-Agent-Research-Map"
ASSETS = Path(__file__).resolve().parents[1] / "web"
ASSET_NAMES = ("index.html", "style.css", "map-core.js", "app.js")


def interactive_outputs(root, taxonomy, papers, topics):
    known = categories(taxonomy)
    exported = []
    for source in papers:
        paper = copy.deepcopy(source)
        paper["publication_date"] = source.get("publication_date", {
            "value": f"{source['year']:04d}", "basis": "year-only", "source": None})
        paper["labels"] = {lang: paper_label(source, lang) for lang in ("en", "zh")}
        paper["topics"] = [slug for slug, topic in topics.items() if set(topic["tags"]) & set(source["tags"])]
        anchor = source["id"].lower().replace(".", "-")
        route = known[source["category"]]["catalog_path"]
        paper["catalog_urls"] = {lang: f"{REPOSITORY}/blob/main/catalog/{route}{suffix}.md#{anchor}"
                                 for lang, suffix in (("en", ""), ("zh", "_cn"))}
        paper["notes_urls"] = {lang: f"{REPOSITORY}/blob/main/{path}" for lang, path in source["notes"].items()}
        exported.append(paper)
    payload = {"schema_version": 1, "repository": REPOSITORY,
               "taxonomy": taxonomy, "topics": topics, "papers": exported}
    encoded = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    assets = {name: (ASSETS / name).read_text(encoding="utf-8") for name in ASSET_NAMES}
    version = hashlib.sha256((encoded + "".join(assets.values())).encode()).hexdigest()[:16]
    site = Path(root) / "site"
    outputs = {site / "map.json": encoded,
               site / "map-data.js": "// Generated by build_catalog.py; do not edit.\nwindow.RESEARCH_MAP = " +
               encoded.replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029").rstrip() + ";\n"}
    for name, content in assets.items():
        outputs[site / name] = content.replace("__ASSET_VERSION__", version)
    outputs[site / ".nojekyll"] = ""
    return outputs
